DATA_DIR = ROOT / "data"
DEFAULT_OUT = DATA_DIR / "_releases"
MANIFEST_PATH = DATA_DIR / "manifest.json"
SCHEMA_VERSION = 1

EXCLUDE_DIRS = {"outputs", "__pycache__", ".ipynb_checkpoints", "_releases"}
EXCLUDE_GLOBS = ("*.tmp", "*.bak", "*.swp", "._*", ".DS_Store", "Thumbs.db")


@dataclass
class ScenarioSpec:
    """Per-scenario packaging contract."""

    scenario_id: str
    description: str
    source_globs: list[str] = field(default_factory=list)
    notes: list[str] = field(default_factory=list)


