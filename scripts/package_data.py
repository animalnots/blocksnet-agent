"""Package per-scenario data into immutable zip archives + write manifest.json.

For each registered scenario (saint-petersburg / vasilievsky-island /
yuzhno-sakhalinsk) creates a zip archive whose root directory is the
scenario name. SHA256 + size for every archive land in ``data/manifest.json``,
which is the single source of truth for ``fetch_data.py`` and for the
GitHub-Releases mapping.

Usage:
    python scripts/package_data.py                     # package all
    python scripts/package_data.py --only saint-petersburg vasilievsky-island
    python scripts/package_data.py --out data/_releases
    python scripts/package_data.py --dry-run           # list what would be packed

Conventions:
- Zip root = ``<scenario_id>/`` (same as ``DATA_DIR/<scenario_id>`` layout).
- ``acc_mx.pickle``, ``blocks_with_services.gpkg``, graph artefacts: always
  included if present.
- ``outputs/`` excluded — runtime artefacts, regenerated by agent runs.
- ``*.tmp``, ``*.bak``, hidden dirs: excluded.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import sys
import zipfile
from dataclasses import dataclass, field
from datetime import datetime, timezone
from pathlib import Path
from typing import Iterable

